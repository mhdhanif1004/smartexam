    <p>Panduan ini disusun untuk membantu peserta (siswa) memahami cara mengikuti Ujian Sekolah Berbasis Komputer (CBT)
        menggunakan SmartExam. Bacalah dengan saksama sebelum ujian dimulai.</p>

    <section id="sebelum"
        class="bg-surface-container-lowest border border-outline-variant rounded-2xl p-lg md:p-xl shadow-sm scroll-mt-24">
        <h2 class="font-title-md text-title-md text-on-surface mb-sm flex items-center gap-sm">
            <span class="material-symbols-outlined text-[20px] text-primary">login</span>
            1. Sebelum Ujian
        </h2>
        <ul class="list-disc pl-md space-y-xs">
            <li>Pastikan Anda telah login ke SmartExam menggunakan username dan password yang diberikan sekolah;</li>
            <li>Masuklah ke ruang ujian sesuai jadwal dan tempat duduk yang telah ditentukan;</li>
            <li>Perhatikan arahan pengawas ruangan.</li>
        </ul>
    </section>

    <section id="token"
        class="bg-surface-container-lowest border border-outline-variant rounded-2xl p-lg md:p-xl shadow-sm scroll-mt-24">
        <h2 class="font-title-md text-title-md text-on-surface mb-sm flex items-center gap-sm">
            <span class="material-symbols-outlined text-[20px] text-primary">vpn_key</span>
            2. Cara Masuk Ujian (Token)
        </h2>
        <p>Untuk memulai ujian, Anda perlu memasukkan <strong>Token Ujian</strong> yang diumumkan oleh pengawas
            ruangan. Ikuti langkah berikut:</p>
        <ul class="list-disc pl-md space-y-xs mt-sm">
            <li>Buka halaman ujian pada jadwal yang tersedia;</li>
            <li>Masukkan token pada kolom yang tersedia, lalu tekan tombol untuk memvalidasi;</li>
            <li>Apabila token benar, ujian akan dimulai. Apabila salah, periksa kembali token atau hubungi pengawas.</li>
        </ul>
        <p class="mt-sm">Token bersifat rahasia dan diberikan langsung oleh pengawas; jangan meminta atau memberikan
            token kepada peserta lain tanpa seizin pengawas.</p>
    </section>

    <section id="waktu"
        class="bg-surface-container-lowest border border-outline-variant rounded-2xl p-lg md:p-xl shadow-sm scroll-mt-24">
        <h2 class="font-title-md text-title-md text-on-surface mb-sm flex items-center gap-sm">
            <span class="material-symbols-outlined text-[20px] text-primary">timer</span>
            3. Aturan Waktu
        </h2>
        <ul class="list-disc pl-md space-y-xs">
            <li>Sistem menampilkan <strong>Timer Mapel</strong> (waktu untuk mengerjakan mata pelajaran) dan
                <strong>Timer Sesi</strong>;</li>
            <li>Ketika waktu utama habis, terdapat <strong>masa toleransi (waktu tambahan/grace)</strong> yang
                ditampilkan sebagai "+MM:SS";</li>
            <li>Apabila waktu habis, sistem akan <strong>mengumpulkan jawaban secara otomatis</strong>;</li>
            <li>Perhatikan sisa waktu agar jawaban dapat dikumpulkan sebelum batas akhir.</li>
        </ul>
    </section>

    <section id="larangan"
        class="bg-surface-container-lowest border border-outline-variant rounded-2xl p-lg md:p-xl shadow-sm scroll-mt-24">
        <h2 class="font-title-md text-title-md text-on-surface mb-sm flex items-center gap-sm">
            <span class="material-symbols-outlined text-[20px] text-primary">block</span>
            4. Larangan Selama Ujian
        </h2>
        <p>Mohon patuhi larangan berikut. Aktivitas di bawah ini akan <strong>tercatat sebagai pelanggaran</strong>
            oleh sistem anti-kecurangan:</p>
        <ul class="list-disc pl-md space-y-xs mt-sm">
            <li>Jangan pindah tab / membuka aplikasi lain selama ujian;</li>
            <li>Jangan keluar dari mode layar penuh (fullscreen);</li>
            <li>Jangan berkomunikasi dengan peserta lain selama ujian berlangsung.</li>
        </ul>
    </section>

    <section id="mengerjakan"
        class="bg-surface-container-lowest border border-outline-variant rounded-2xl p-lg md:p-xl shadow-sm scroll-mt-24">
        <h2 class="font-title-md text-title-md text-on-surface mb-sm flex items-center gap-sm">
            <span class="material-symbols-outlined text-[20px] text-primary">checklist</span>
            5. Cara Mengerjakan & Mengumpulkan
        </h2>
        <ul class="list-disc pl-md space-y-xs">
            <li>Pilih jawaban dengan mengklik opsi pada tiap soal; jawaban <strong>tersimpan secara otomatis</strong>;</li>
            <li>Anda dapat <strong>menandai soal ragu-ragu</strong> agar mudah ditinjau kembali sebelum dikumpulkan;</li>
            <li>Periksa kembali seluruh jawaban, lalu tekan tombol <strong>Kumpulkan</strong> untuk menyelesaikan
                ujian;</li>
            <li>Setelah dikumpulkan, jawaban tidak dapat diubah kembali.</li>
        </ul>
    </section>

    <section id="kendala"
        class="bg-surface-container-lowest border border-outline-variant rounded-2xl p-lg md:p-xl shadow-sm scroll-mt-24">
        <h2 class="font-title-md text-title-md text-on-surface mb-sm flex items-center gap-sm">
            <span class="material-symbols-outlined text-[20px] text-primary">support_agent</span>
            6. Kendala Teknis
        </h2>
        <p>Apabila mengalami kendala teknis (misalnya tidak dapat login, token tidak valid, atau masalah tampilan),
            segera <strong>hubungi pengawas ruangan</strong> untuk dibantu.</p>
    </section>
